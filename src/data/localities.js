export const LOC_BY_ID = Object.fromEntries(LOCALITIES.map((l) => [l.id, l]));

export const distKm = (a, b, c, d) => {
  const R = 6371,
    r = (x) => (x * Math.PI) / 180;
  const dl = r(c - a),
    dn = r(d - b);
  const h = Math.sin(dl / 2) ** 2 + Math.cos(r(a)) * Math.cos(r(c)) * Math.sin(dn / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(h));
};

export const nearestLocality = (lat, lng) =>
  LOCALITIES.reduce((b, l) => {
    const d = distKm(lat, lng, l.lat, l.lng);
    return !b || d < b.d ? { l, d } : b;
  }, null).l;
